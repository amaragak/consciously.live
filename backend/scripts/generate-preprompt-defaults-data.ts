/**
 * Regenerate lambdas/_shared/preprompts/preprompt-defaults-data.ts from the
 * repo default files (preprompts/defaults/*.txt). Style guides are NOT copied:
 * they come from STYLE_GUIDE_BY_TYPE (style-instructions-data.ts), same as before.
 *
 * Usage:
 *   npx tsx scripts/generate-preprompt-defaults-data.ts          # write
 *   npx tsx scripts/generate-preprompt-defaults-data.ts --check  # exit 1 if stale
 */
import fs from "node:fs";
import path from "node:path";
import { PREPROMPT_REGISTRY } from "../lambdas/_shared/preprompts/preprompt-registry";
import { readRepoPrepromptText } from "../lambdas/_shared/preprompts/preprompt-repo-files";

const OUT = path.resolve(
  __dirname,
  "../lambdas/_shared/preprompts/preprompt-defaults-data.ts",
);

export function renderPrepromptDefaultsData(): string {
  const prompts = PREPROMPT_REGISTRY.filter((e) => e.group === "preprompt");
  const guides = PREPROMPT_REGISTRY.filter((e) => e.group === "style_guide");
  const lines: string[] = [
    "/**",
    " * GENERATED by scripts/generate-preprompt-defaults-data.ts — do not edit by hand.",
    " * Source: preprompts/defaults/*.txt (pre-prompts) and STYLE_GUIDE_BY_TYPE (style guides).",
    " * Lambdas cannot read repo files at runtime; this is the fallback when Dynamo is unreachable.",
    " */",
    'import { STYLE_GUIDE_BY_TYPE } from "../style-instructions-data";',
    "",
    "export const PREPROMPT_DEFAULTS: Record<string, string> = {",
  ];
  for (const e of prompts) {
    lines.push(
      `  ${JSON.stringify(e.id)}: ${JSON.stringify(readRepoPrepromptText(e))},`,
    );
  }
  for (const e of guides) {
    lines.push(
      `  ${JSON.stringify(e.id)}: STYLE_GUIDE_BY_TYPE[${JSON.stringify(e.meditationType)}]?.trim() ?? "",`,
    );
  }
  lines.push("};", "");
  return lines.join("\n");
}

function main() {
  const next = renderPrepromptDefaultsData();
  const check = process.argv.includes("--check");
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (check) {
    if (prev !== next) {
      console.error(
        "preprompt-defaults-data.ts is stale. Run: npx tsx scripts/generate-preprompt-defaults-data.ts",
      );
      process.exit(1);
    }
    console.log("preprompt-defaults-data.ts is up to date");
    return;
  }
  fs.writeFileSync(OUT, next);
  console.log(`Wrote ${OUT}`);
}

if (require.main === module) main();
